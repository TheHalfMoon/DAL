# ruff: noqa: E501
"""Generate release-candidate documents whose claims are copied verbatim from the frozen ledger.

Outputs: the README frozen-results block, a tool/model card, a Hugging Face card draft, and
release notes. Nothing here publishes anything; arXiv, Hugging Face, and release tagging remain
founder actions.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "registry" / "p08_sg000023_paper_evidence"
README_PATH = ROOT / "README.md"
RELEASE_DIR = ROOT / "docs" / "release"
FROZEN_CLAIM_SET_SHA256 = "ef2e347d9ef4298deb68a422c063aa92e9968ae5d00fb0c511576448eb7a2b9b"

BEGIN = "<!-- DAL:FROZEN-RESULTS:BEGIN (generated by tools/build_sg000024_release_docs.py; do not edit) -->"
END = "<!-- DAL:FROZEN-RESULTS:END -->"

DISCLAIMER = (
    "**Research use only.** DAL is not a medical device, has not been clinically validated, and must "
    "not be used for diagnosis, treatment, triage, or any patient-care decision. Nothing here supports "
    "a claim of clinical safety, deployment fitness, or regulatory readiness."
)


def _load(name: str) -> Any:
    return json.loads((PACKAGE / name).read_text(encoding="utf-8"))


def _claims() -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    freeze = _load("claim_freeze_manifest.json")
    if freeze["claim_freeze"]["claim_set_sha256"] != FROZEN_CLAIM_SET_SHA256:
        raise ValueError("claim set differs from the SG-000024 frozen binding")
    ledger = _load("claim_ledger.json")
    affirmative = [c for c in ledger["claims"] if c["public_use"] == "affirmative-claim"]
    limitations = [c for c in ledger["claims"] if c["public_use"] == "limitation-statement"]
    return affirmative, limitations


def _claim_lines(claims: list[dict[str, Any]]) -> list[str]:
    return [f"- {claim['text']} (`{claim['claim_id']}`)" for claim in claims]


def _results_block() -> str:
    affirmative, limitations = _claims()
    lines = [
        BEGIN,
        "",
        "Frozen P08 results. Each statement is copied verbatim from the frozen claim ledger "
        f"(claim-set SHA-256 `{FROZEN_CLAIM_SET_SHA256}`).",
        "",
        "**Findings**",
        "",
        *_claim_lines(affirmative),
        "",
        "**Limitations**",
        "",
        *_claim_lines(limitations),
        "",
        END,
    ]
    return "\n".join(lines)


