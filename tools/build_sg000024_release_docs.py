def _release_notes() -> str:
    affirmative, limitations = _claims()
    lines = [
        "<!-- Generated by tools/build_sg000024_release_docs.py; do not edit. -->",
        "# DAL release notes (draft; no tag has been created)",
        "",
        DISCLAIMER,
        "",
        "## Contents",
        "",
        "- Frozen P08 final-evaluation evidence (`registry/p08_sg000022_final_evaluation/`).",
        "- Paper evidence package, related-work record, and claim freeze (`registry/p08_sg000023_*`).",
        "- Manuscript source (`paper/`), generated from the frozen package.",
        "",
        "## Frozen findings",
        "",
        *_claim_lines(affirmative),
        "",
        "## Known limitations",
        "",
        *_claim_lines(limitations),
        "",
        "## Not included",
        "",
        "- Model weights (pending a founder license decision).",
        "- Fine-tuning notebooks (deferred; they require execution evidence).",
        "- arXiv submission and Hugging Face publication (founder-account actions).",
        "",
    ]
    return "\n".join(lines)


def _readme(current: str) -> str:
    if current.count(BEGIN) != 1 or current.count(END) != 1:
        raise ValueError("README must contain exactly one frozen-results block")
    head, rest = current.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + _results_block() + tail


def build_outputs() -> dict[Path, str]:
    return {
        README_PATH: _readme(README_PATH.read_text(encoding="utf-8")),
        RELEASE_DIR / "MODEL_CARD.md": _model_card(),
        RELEASE_DIR / "HUGGINGFACE_CARD_DRAFT.md": _huggingface_card(),
        RELEASE_DIR / "RELEASE_NOTES_DRAFT.md": _release_notes(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Build SG-000024 release-candidate documents")
    parser.add_argument(
        "--check", action="store_true", help="fail unless committed documents match a rebuild"
    )
    args = parser.parse_args()
    outputs = build_outputs()
    if args.check:
        stale = [
            path.relative_to(ROOT).as_posix()
            for path, text in outputs.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        for name in stale:
            print(f"release document differs from deterministic rebuild: {name}")
        if stale:
            return 1
        print(f"SG-000024 release documents check passed: {len(outputs)} files")
        return 0
    RELEASE_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"SG-000024 release documents built: {len(outputs)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
